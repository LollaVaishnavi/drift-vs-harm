"""Screenshot the tool's real HTML report, and fail if the verdict is invisible.

The report is generated here from the tool's own render_html, not photographed from
whatever happened to be on disk, so a stale report cannot be captured. After rendering,
the script reads back the computed style of the verdict badge and fails if it is not
visible or has no contrast, because a screenshot tool is the only thing in the pipeline
that can see pixels, and an invisible headline has shipped before.

Dev-time only. Needs playwright and chromium; not part of `make verify`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from driftharm.config import load_policy  # noqa: E402
from driftharm.harness import build_baseline, run_suite  # noqa: E402
from driftharm.report import render_html  # noqa: E402
from driftharm.scenarios import default_suite  # noqa: E402

REPORTS = ROOT / "reports"
OUT_PNG = ROOT / "docs" / "img" / "report.png"
MANIFEST = ROOT / "docs" / "img" / "manifest.json"


def _relative_luminance(rgb: tuple[float, float, float]) -> float:
    def channel(c: float) -> float:
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(x) for x in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def _parse_rgb(value: str) -> tuple[float, float, float]:
    body = value.replace("rgba(", "").replace("rgb(", "").rstrip(")")
    nums = [float(n) for n in body.split(",")[:3]]
    return nums[0], nums[1], nums[2]


def _contrast(fg: str, bg: str) -> float:
    lf = _relative_luminance(_parse_rgb(fg))
    lb = _relative_luminance(_parse_rgb(bg))
    lighter, darker = max(lf, lb), min(lf, lb)
    return (lighter + 0.05) / (darker + 0.05)


def main() -> int:
    policy = load_policy()
    outcomes = run_suite(policy, default_suite(), baseline=build_baseline(policy))
    REPORTS.mkdir(exist_ok=True)
    report_html = REPORTS / "report.html"
    report_html.write_text(render_html(outcomes))
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)

    with sync_playwright() as p:
        browser = p.chromium.launch(args=["--no-sandbox"])
        page = browser.new_page(viewport={"width": 960, "height": 900}, device_scale_factor=2)
        page.goto(report_html.resolve().as_uri())
        page.wait_for_selector(".verdict")

        reading = page.evaluate(
            """() => {
              const badge = document.querySelector('.verdict');
              if (!badge) return null;
              const s = getComputedStyle(badge);
              return {color: s.color, background: s.backgroundColor,
                      visible: badge.offsetWidth > 0 && badge.offsetHeight > 0,
                      text: badge.textContent};
            }"""
        )
        if reading is None or not reading["visible"]:
            browser.close()
            raise SystemExit("verdict badge is missing or has zero size")
        ratio = _contrast(reading["color"], reading["background"])
        if ratio < 4.5:
            browser.close()
            raise SystemExit(f"verdict badge contrast {ratio:.1f} is below 4.5:1 (illegible)")

        page.screenshot(path=str(OUT_PNG), full_page=True)
        browser.close()

    MANIFEST.write_text(json.dumps({
        "image": str(OUT_PNG.relative_to(ROOT)),
        "source_report": "generated by driftharm.report.render_html in this run",
        "verdict_text": reading["text"],
        "verdict_contrast_ratio": round(ratio, 1),
    }, indent=2) + "\n")
    print(f"wrote {OUT_PNG.relative_to(ROOT)} (verdict contrast {ratio:.1f}:1)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
